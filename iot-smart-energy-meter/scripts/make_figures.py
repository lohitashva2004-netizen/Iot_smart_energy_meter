from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from energy_meter.simulate import FS, calibrate_frontend, measure, window_times
from energy_meter.waveforms import BIAS_V, Frontend, load_current, mains_voltage

OUT = Path(__file__).resolve().parents[1] / "docs" / "images"
NAVY, RED, BLUE, GREEN, GREY = "#1f3a68", "#d9534f", "#3b78c3", "#3a9d5d", "#9aa5b1"
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True, "grid.alpha": 0.25})


def waveforms():
    rng = np.random.default_rng(5)
    fe = Frontend()
    t = window_times()
    v_adc, i_adc = fe.sample(mains_voltage(t), load_current(t, 100, 0.9), rng)
    n = int(FS * 2 / 50)                                  # first two cycles
    fig, ax = plt.subplots(2, 1, figsize=(8, 5), sharex=True)
    ax[0].plot(t[:n] * 1000, v_adc[:n], color=NAVY, lw=1.2)
    ax[0].axhline(BIAS_V, color=RED, ls="--", lw=1, label="1.65 V bias (2 x 10 kΩ divider)")
    ax[0].set(ylabel="ZMPT101B → ADC (V)", title="What the ESP32 ADC sees: AC riding on a DC bias (model, 100 W load, PF 0.9)"); ax[0].legend(frameon=False)
    ax[1].plot(t[:n] * 1000, i_adc[:n], color=BLUE, lw=1.2)
    ax[1].axhline(BIAS_V, color=RED, ls="--", lw=1)
    ax[1].set(ylabel="SCT-013 → ADC (V)", xlabel="Time (ms)")
    fig.tight_layout(); fig.savefig(OUT / "model_waveforms.png", dpi=140); plt.close(fig)


def resolution_study(trials=40):
    cts = [("SCT-013-005 (5 A : 1 V)", 5.0, GREEN), ("SCT-013-000, 100 Ω burden (20 A/V)", 20.0, BLUE), ("SCT-013-030 (30 A : 1 V)", 30.0, GREY)]
    loads = np.logspace(np.log10(2), np.log10(2000), 14)
    rng = np.random.default_rng(11)
    fig, ax = plt.subplots(1, 2, figsize=(11, 4))
    stats = {}
    for name, apv, color in cts:
        fe = Frontend(ct_amps_per_volt=apv, noise_mv_rms=2.0)
        vs, is_ = calibrate_frontend(fe, rng)
        err = []
        for p in loads:
            r = [measure(p, 1.0, fe, vs, is_, rng) for _ in range(trials)]
            err.append(100 * (np.mean([x["i_rms"] for x in r]) - r[0]["i_true"]) / r[0]["i_true"])
        ax[0].plot(loads, err, "o-", ms=3.5, color=color, label=name)
        stats[name] = (loads, err, fe, vs, is_)
    ax[0].set_xscale("log"); ax[0].axhline(0, color="k", lw=0.8)
    ax[0].set(title="Irms error vs resistive load (ADC noise 2 mV RMS)", xlabel="Real load power (W)", ylabel="Irms error (%)", ylim=(-10, 300))
    ax[0].axvline(4.8, color=RED, ls=":", lw=1); ax[0].text(4.8 * 1.07, 250, "report's\n4.8 W bulb", color=RED, fontsize=8)
    ax[0].legend(frameon=False, fontsize=8)

    _, _, fe, vs, is_ = stats["SCT-013-000, 100 Ω burden (20 A/V)"]
    app, real = [], []
    for p in loads:
        r = [measure(p, 1.0, fe, vs, is_, rng) for _ in range(trials)]
        app.append(100 * (np.mean([x["apparent_va"] for x in r]) - p) / p)
        real.append(100 * (np.mean([x["real_w"] for x in r]) - p) / p)
    ax[1].plot(loads, app, "o-", ms=3.5, color=RED, label="Vrms × Irms (what the report computes)")
    ax[1].plot(loads, real, "s-", ms=3.5, color=NAVY, label="mean(v(t)·i(t)) (real power)")
    ax[1].set_xscale("log"); ax[1].axhline(0, color="k", lw=0.8)
    ax[1].set(title="Power error vs load, same front end (resistive load)", xlabel="Real load power (W)", ylabel="Power error (%)", ylim=(-10, 300))
    ax[1].legend(frameon=False, fontsize=8)
    fig.tight_layout(); fig.savefig(OUT / "resolution_study.png", dpi=140); plt.close(fig)
    return loads, stats, app, real


def write_study_doc(trials=60):
    """docs/measurement_study.md: table generated from the same model, so text and figure agree."""
    rng = np.random.default_rng(21)
    loads = [5, 10, 25, 50, 100, 500]
    rows = []
    cfgs = [("SCT-013-005", 5.0), ("SCT-013-000 / 100 Ω", 20.0), ("SCT-013-030", 30.0)]
    cal = {n: (lambda fe: (fe, *calibrate_frontend(fe, rng)))(Frontend(ct_amps_per_volt=a, noise_mv_rms=2.0)) for n, a in cfgs}
    for p in loads:
        cells = []
        for n, _ in cfgs:
            fe, vs, is_ = cal[n]
            r = [measure(p, 1.0, fe, vs, is_, rng) for _ in range(trials)]
            cells.append(f"{100 * (np.mean([x['i_rms'] for x in r]) - r[0]['i_true']) / r[0]['i_true']:+.0f}%")
        fe, vs, is_ = cal["SCT-013-000 / 100 Ω"]
        r = [measure(p, 1.0, fe, vs, is_, rng) for _ in range(trials)]
        a_err = 100 * (np.mean([x["apparent_va"] for x in r]) - p) / p
        w_err = 100 * (np.mean([x["real_w"] for x in r]) - p) / p
        rows.append(f"| {p} W | {' | '.join(cells)} | {a_err:+.0f}% | {w_err:+.1f}% |")
    md = f"""# Measurement study: how low can this front end go?

*Generated by `scripts/make_figures.py` from the model in `src/energy_meter`. The ADC noise (2 mV RMS), 5 kHz sampling and 230 V / 50 Hz mains are **assumptions**, not measurements of the prototype. Use the study to understand trends, then verify on hardware.*

## Why look at this?

The ESP32's ADC has 12 bits over 3.3 V, i.e. about **0.8 mV per code**, plus analog noise. A mains current CT produces a very small signal at light loads. With an SCT-013-000 (100 A : 50 mA) and a 100 Ω burden, a 5 W lamp (about 22 mA at 230 V, unity power factor) gives a burden voltage of roughly **1 mV RMS**: about one ADC code.

## Results (resistive load, PF = 1)

![Resolution study](images/resolution_study.png)

| True load | Irms error: SCT-013-005 | Irms error: SCT-013-000 / 100 Ω | Irms error: SCT-013-030 | Vrms×Irms power error (100 Ω setup) | mean(v·i) power error (same setup) |
|---|---|---|---|---|---|
{chr(10).join(rows)}

## Take-aways

1. **RMS current at light loads is biased upward by noise.** Independent noise adds in quadrature, so a noise floor equal to roughly 40 mA RMS (2 mV x 20 A/V) inflates a 22 mA reading. Zero-load calibration (`zero` serial command) and quadrature subtraction help, but the floor is also the resolution limit.
2. **The right CT depends on the loads you care about.** A smaller-range CT (SCT-013-005) resolves low currents far better but clips above about 5 A. The 100 A-class CT is a good fit from roughly 50 W up and a poor one near 5 W.
3. **Real power is far more robust than V x I at low load.** Averaging the product v(t)·i(t) cancels uncorrelated noise, so the same front end that overstates apparent power by hundreds of percent at 5 W reads real power within a few percent. It also handles power factor, which `Vrms x Irms` cannot. This is exactly the "Power Factor and Real Power" item in the project's future scope, and the model suggests it is also the most valuable low-load accuracy fix.
4. **Practical advice:** validate the meter with a 40-100 W load of known power before trusting readings near 5 W.

*Caveat:* sequential ADC reads put a small time offset between the voltage and current samples. At 5 kHz per channel that is on the order of a degree of phase at 50 Hz, which matters for power factor and should be corrected (interpolation or a phase-shift constant) in a hardware implementation.
"""
    (OUT.parent / "measurement_study.md").write_text(md, encoding="utf-8")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    write_study_doc()
    waveforms()
    loads, stats, app, real = resolution_study()
